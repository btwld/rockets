import type { Type } from '@nestjs/common';
import type { RateLimitStoreInterface } from '@concepta/rockets-core';

/** One rate-limit dimension: requests per fixed window. */
export interface RocketsAuthRateLimitWindow {
  readonly limit: number;
  readonly windowMs: number;
}

/**
 * Request-throttling configuration for Rockets Auth's own public routes,
 * built on core's rate-limit port (`@RateLimit` + `RateLimitGuard` +
 * `RateLimitStoreInterface`).
 *
 * Two dimensions, both enforced at once on every guarded auth route:
 *
 * - `ip` — a coarse per-IP volume ceiling. It is not overridden per
 *   route, so rotating the account field from one source cannot escape
 *   it (credential stuffing, signup/recovery spam).
 * - `default` — fine per-`(ip, account)` limits. Keying on the pair
 *   means an attacker only throttles themselves, never locks a victim
 *   out of login. Routes tighten this one with `@RateLimit`.
 *
 * `store` swaps the backing counter store, and is the way to do it: the
 * auth registration provides `RATE_LIMIT_STORE_TOKEN` itself, and a
 * module resolves its own imports before the global registry, so a
 * provider an app declares for that token elsewhere serves the app's own
 * routes while the auth routes keep this one. One exception, and it is
 * upstream's: the `/signup` controller is generated by
 * `CrudModule.forFeature` into a module that accepts no imports, so it
 * reads the global registry — an app that registers the token in a
 * `@Global()` module BEFORE Rockets Auth takes that route's counters with
 * it. The default is core's
 * `InMemoryRateLimitStore` — per process, which is also what the previous
 * engine shipped. A multi-instance deployment wants a shared backend
 * behind the same `RateLimitStoreInterface` (`CONFIGURATION.md` §7d shows
 * a dynamic-repository one).
 *
 * `maxKeys` bounds what the in-memory store tracks, for the same reason:
 * it is constructed here, so core's `RATE_LIMIT_MAX_KEYS_TOKEN` has to be
 * provided by this registration to reach it.
 */
export interface RocketsAuthThrottlingOptions {
  readonly ip?: RocketsAuthRateLimitWindow;
  readonly default?: RocketsAuthRateLimitWindow;
  readonly store?: Type<RateLimitStoreInterface>;
  /**
   * Key cap for the default in-memory store. Ignored when `store` is a
   * class that does not read `RATE_LIMIT_MAX_KEYS_TOKEN`.
   */
  readonly maxKeys?: number;
}
